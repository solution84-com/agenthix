/**
 * The form of a connection's committed snapshot (core/snapshot/<connection>.json): every declared type of the
 * connection, by name, with its shape. A named type declared in core is a `ref` to its own entry; anything else is
 * written out where it is used.
 */

export type Primitive =
  | 'string' | 'number' | 'boolean' | 'bigint' | 'null' | 'undefined' | 'void' | 'unknown' | 'any' | 'never'
  | 'object'
  /** A `Date`: superjson carries it as a date. */
  | 'date'

export type Shape =
  | { type: Primitive }
  | { literal: string | number | boolean }
  | { ref: string }
  | { param: string }
  | { array: Shape }
  | { tuple: Shape[] }
  | { union: Shape[] }
  | { intersection: Shape[] }
  | { fields: Record<string, Field>; index?: { key: 'string' | 'number'; value: Shape } }
  /** What the snapshot does not take apart (a function, a conditional type, a `Map`): compared as written. */
  | { text: string }

export type Field = {
  type: Shape
  optional?: true
  /** The `@deprecated` mark's text, as written. */
  deprecated?: string
}

export type Entry = {
  /** Where it is declared, relative to core/src. Informational: moving a type is no change to the protocol. */
  file: string
  /** A generic declaration's type parameters; a use of it is written out, instantiated, where it is used. */
  params?: string[]
  deprecated?: string
  shape: Shape
}

export type Snapshot = {
  $comment: string
  connection: string
  /** The connection's protocol version when the snapshot was taken. */
  version: string
  types: Record<string, Entry>
}

export const SNAPSHOT_COMMENT =
  'Generated by core\'s `npm run snapshot:update`; checked by core\'s tests (src/__tests__/protocolSnapshot.test.ts). ' +
  'Do not edit by hand. A `ref` names another entry; `date` is a superjson date; `text` is compared as written.'

/** A stable string for a shape, for matching and equality: keys in a fixed order. */
export function canonical(value: unknown): string {
  return JSON.stringify(sortKeys(value))
}

export function sortKeys(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(sortKeys)
  if (value && typeof value === 'object') {
    const out: Record<string, unknown> = {}
    for (const k of Object.keys(value).sort()) out[k] = sortKeys((value as Record<string, unknown>)[k])
    return out
  }
  return value
}

/** A short rendering of a shape for messages: `string | null`, `RunStatus[]`, `{ id, name }`. */
export function describeShape(s: Shape): string {
  if ('type' in s) return s.type
  if ('literal' in s) return JSON.stringify(s.literal)
  if ('ref' in s) return s.ref
  if ('param' in s) return s.param
  if ('array' in s) return `${describeShape(s.array)}[]`
  if ('tuple' in s) return `[${s.tuple.map(describeShape).join(', ')}]`
  if ('union' in s) return s.union.map(describeShape).join(' | ')
  if ('intersection' in s) return s.intersection.map(describeShape).join(' & ')
  if ('fields' in s) return `{ ${Object.keys(s.fields).join(', ')} }`
  return s.text
}

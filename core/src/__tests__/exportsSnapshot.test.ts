/**
 * Every name core's package entry points export, against core/snapshot/exports.json, the snapshot the Release's break
 * scan compares with the previous release's (scripts/release/breaks.mjs): a name gone is a breaking change, one added
 * is not. A difference fails here; `npm run snapshot:update` in core records it, and a removal is then a commit marked
 * breaking (docs/architecture/versioning.md, *The release's surface snapshots*).
 */
import ts from 'typescript'
import { expect, it } from 'vitest'
import { CORE_SRC, SNAPSHOT_DIR, coreProgram } from './protocolSnapshot/connections.js'

const env = (globalThis as { process?: { env: Record<string, string | undefined> } }).process?.env ?? {}
const UPDATE = env.PROTOCOL_SNAPSHOT_UPDATE === '1'
const FILE = `${SNAPSHOT_DIR}/exports.json`
const COMMENT = "Generated by core's `npm run snapshot:update`; checked by core's tests (src/__tests__/exportsSnapshot.test.ts). Do not edit by hand. Each entry is `<entry point>: <exported name>`; a removed entry is a breaking change."

type Exports = { types?: string; default?: string }

/** `./dist/client/index.js` in package.json's `exports` is `src/client/index.ts`. */
function entryPoints(): [string, string][] {
  const manifest = JSON.parse(ts.sys.readFile(`${CORE_SRC}/../package.json`)!) as { exports: Record<string, Exports> }
  return Object.entries(manifest.exports).map(([entry, target]) =>
    [entry, ts.sys.resolvePath(`${CORE_SRC}/${target.default!.replace(/^\.\/dist\//, '').replace(/\.js$/, '.ts')}`)])
}

function exportedNames(): string[] {
  const program = coreProgram()
  const checker = program.getTypeChecker()
  return entryPoints().flatMap(([entry, file]) => {
    const source = program.getSourceFile(file)
    if (!source) throw new Error(`core's entry point ${entry} has no source at ${file}`)
    const module = checker.getSymbolAtLocation(source)
    return module ? checker.getExportsOfModule(module).map(symbol => `${entry}: ${symbol.getName()}`) : []
  }).sort()
}

it("core's exported names match core/snapshot/exports.json @SC-2193", () => {
  const now = exportedNames()
  expect(now.length).toBeGreaterThan(0)
  const text = ts.sys.readFile(FILE)
  const committed = text === undefined ? null : (JSON.parse(text) as { entries: string[] }).entries
  if (UPDATE) {
    if (JSON.stringify(committed) !== JSON.stringify(now)) {
      ts.sys.writeFile(FILE, `${JSON.stringify({ $comment: COMMENT, entries: now }, null, 2)}\n`)
    }
    return
  }
  if (!committed) throw new Error('no snapshot at core/snapshot/exports.json; run `npm run snapshot:update` in core')
  const removed = committed.filter(name => !now.includes(name))
  const added = now.filter(name => !committed.includes(name))
  expect({ removed, added }, "core's exports differ from core/snapshot/exports.json: record them with `npm run snapshot:update` in core; a removal ships only in a commit marked breaking").toEqual({ removed: [], added: [] })
})

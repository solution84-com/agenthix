/**
 * The host service's surfaces against their committed snapshots (host/snapshot/): the `agenthix` commands and options,
 * the start-up settings it reads, and the names an installation creates. The Release's break scan
 * (scripts/release/breaks.mjs) compares each with the previous release's: an entry gone is a breaking change, one
 * added is not. A difference fails here; `npm run snapshot:update` in host records it, and a removal then ships only
 * in a commit marked breaking (docs/architecture/versioning.md, *The release's surface snapshots*).
 */
import fs from 'node:fs'
import path from 'node:path'
import { describe, expect, it } from 'vitest'
import { cliEntries, rowEntries } from './surfaceSnapshot/cli'
import { namesEntries } from './surfaceSnapshot/names'
import { settingsEntries } from './surfaceSnapshot/settings'

const UPDATE = process.env.SURFACE_SNAPSHOT_UPDATE === '1'
const DIR = path.resolve(import.meta.dirname, '../../snapshot')

const SURFACES = [
  { name: 'cli', what: 'The agenthix commands and options', entries: cliEntries },
  { name: 'settings', what: "The host service's start-up settings", entries: settingsEntries },
  { name: 'names', what: 'The names an installation creates', entries: namesEntries },
]

describe('the host service matches its surface snapshots', () => {
  for (const surface of SURFACES) {
    it(surface.name, () => {
      const file = path.join(DIR, `${surface.name}.json`)
      const now = surface.entries()
      expect(now.length).toBeGreaterThan(0)
      const committed = fs.existsSync(file) ? (JSON.parse(fs.readFileSync(file, 'utf8')) as { entries: string[] }).entries : null
      if (UPDATE) {
        if (JSON.stringify(committed) === JSON.stringify(now)) return
        const comment = `Generated by host's \`npm run snapshot:update\`; checked by host's tests (src/__tests__/surfaceSnapshot.test.ts). Do not edit by hand. ${surface.what}; a removed entry is a breaking change.`
        fs.mkdirSync(DIR, { recursive: true })
        fs.writeFileSync(file, `${JSON.stringify({ $comment: comment, entries: now }, null, 2)}\n`)
        return
      }
      if (!committed) throw new Error(`no snapshot at host/snapshot/${surface.name}.json; run \`npm run snapshot:update\` in host`)
      const removed = committed.filter(e => !now.includes(e))
      const added = now.filter(e => !committed.includes(e))
      expect({ removed, added }, `${surface.what} differ from host/snapshot/${surface.name}.json: record them with \`npm run snapshot:update\` in host; a removal ships only in a commit marked breaking`).toEqual({ removed: [], added: [] })
    })
  }
})

describe("a help row's commands, words and options", () => {
  const row = (usage: string, detail = '') => rowEntries({ group: 'hq', usage, does: '', detail })

  it('alternatives name each command, and a bracket of words are words it takes', () => {
    expect(row('hq suspend | resume')).toEqual(['hq suspend', 'hq resume'])
    expect(row('backup [export]')).toEqual(['backup', 'backup export'])
    expect(row('front-door add-installation | remove-installation <namespace>')).toEqual(['front-door add-installation', 'front-door remove-installation'])
  })

  it("an option's values are not words, and options in the detail count", () => {
    expect(row('upgrades host [--launcher on | off | --image <name or id>]')).toEqual(['upgrades host', 'upgrades host --launcher', 'upgrades host --image'])
    expect(row('install', '--address <address> answers it; --yes takes the default.')).toEqual(['install', 'install --address', 'install --yes'])
    expect(row('restore --from <folder or file> [<hq address> <code>]')).toEqual(['restore', 'restore --from'])
    expect(row('front-door', 'from a script, add --take-ports-80-and-443.')).toEqual(['front-door', 'front-door --take-ports-80-and-443'])
  })
})

/**
 * manifestActions
 * ===============
 * Wasp server actions for HITL manifest approval / rejection.
 *
 * The PENDING_APPROVAL run row lives on site, not in hq's own database — hq's
 * schema declares no AgentRun model at all (dropped in plan 5d-2 task 10, the
 * "shed"; runtimeModelsAbsent.test.ts pins it). Every read here goes through
 * `siteRuntimeStore.getRun`, and every write to the run row itself goes
 * through the channel (`approveRun` / `rejectRun`).
 *
 * Resolving which site a runId lives on — there is no local row to read a
 * siteId off, and the channel is site-keyed — works two ways:
 *   - A TASK run: `TaskComment.runId` (written by TaskRunner's own status
 *     listener when the run went RUN_BLOCKED) names the task; the task's project
 *     resolves the site (`dispatchService.resolveSiteIdForTask`).
 *   - A CHAT run: no hq-local row carries a runId→session mapping at all
 *     (chat manifest-pending state has always been socket-only) — the caller
 *     supplies `sessionId`, which the client already has (the same
 *     `manifestPendingApproval` payload that carries `runId`), and
 *     `dispatchService.resolveSiteIdForSession` resolves from there.
 *
 * approveManifest — human approves the pending manifest; starts the next run
 *                   of the task or the conversation, which alone is given it.
 * rejectManifest  — human rejects the manifest; holds the task (task runs) or
 *                   notifies the session (chat runs).
 *
 * Only the newest run's request can be answered: one replaced by anything newer
 * in its task or conversation is refused with a plain sentence
 * (manifestRequests.ts).
 */
// NOTE: ApproveManifest / RejectManifest types are generated by Wasp at build time.
// Until wasp start/build is re-run, context is typed as `any`.

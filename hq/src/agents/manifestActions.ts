/** A newer run of the task is queued or going: approving the older request would overwrite it. */
const TASK_RUN_UNDER_WAY: TaskRunState[] = ['RUN_ACTIVE', 'RUN_QUEUED', 'RUN_THROTTLED']

/** Refuses a request that can no longer be answered, replacing it on the site when it was only overtaken. */
async function requireCurrentRequest(siteId: string, run: RunRow): Promise<void> {
  if (run.manifestStatus === 'SUPERSEDED') throw new HttpError(409, REPLACED_REQUEST_REFUSAL)
  if (run.manifestStatus !== 'PENDING_APPROVAL') {
    throw new HttpError(400, `Run is not pending approval (status: ${run.manifestStatus})`)
  }
  if (!(await requestIsCurrent(siteId, run))) {
    await replaceRequestOnSite(siteId, run.id)
    throw new HttpError(409, REPLACED_REQUEST_REFUSAL)
  }
}

function requireRunNamed(args: ApproveManifestArgs | undefined): void {
  if (typeof args?.runId !== 'string' || args.runId === '') throw new HttpError(400, 'Name the run')
  if (args.sessionId !== undefined && typeof args.sessionId !== 'string') throw new HttpError(400, 'A session id is text')
}

export const approveManifest = async (
  args: ApproveManifestArgs,
  context: any,
): Promise<ManifestAnswerResult> => {
  if (!context.user) throw new HttpError(401)
  requireRunNamed(args)
  return approveRequest(args, context.user.id)
}

/**
 * Approves a run's request as `userId`: the one path a request is approved by, from its card or from a
 * conversation that commissioned the run (conversations/work/tasks).
 */
export async function approveRequest(args: ApproveManifestArgs, userId: string): Promise<ManifestAnswerResult> {
  const { siteId, run, session, agent } = await resolveManifestRunContext(args.runId, args.sessionId)

  await assertCanMutateManifest(session, userId, 'approve')
  await requireCurrentRequest(siteId, run)

  // Answered, by whoever: the request no longer waits in anyone's notifications.
  const answeredTaskId = run.taskId ?? session.taskId

  if (run.taskId) {
    const taskId = run.taskId
    const task = await prisma.task.findUnique({ where: { id: taskId }, select: { runState: true, runStartedBy: true, runOnBehalfOfUserId: true } })
    if (task && TASK_RUN_UNDER_WAY.includes(task.runState)) throw new HttpError(409, REPLACED_REQUEST_REFUSAL)
    // The request is marked APPROVED on site first, THEN the task's next run is
    // queued and dispatched through the ordinary claim path; that run is given
    // what was approved, as the newest earlier run's request (site's
    // nextRunApproval.ts), and the run after it nothing.
    const { approved } = await siteRuntimeStore.approveRun(siteId, args.runId, userId)
    // Missing, answered or overtaken on the site since it was read here.
    if (!approved) throw new HttpError(409, REPLACED_REQUEST_REFUSAL)
    // A person approving a tool does not make the run theirs: a run the pulse
    // or a schedule started is re-run as one (adr-0087). Every claimed task
    // records its starter, and one it cannot read is never taken for a person.
    // Their approval does put it back at depth 0 (adr-0091): a person queued it.
    // Nor does it change whose behalf the run is on: the re-run keeps its starter.
    const startedBy = parseRunStartedBy(task?.runStartedBy) ?? 'pulse'
    const { count } = await prisma.task.updateMany({
      where: { id: taskId, runState: { notIn: TASK_RUN_UNDER_WAY } },
      data: askedToStart(startedBy, personQueuer(userId), 'manifest approved — re-queued'),
    })
    // A newer run was queued between the read above and here: it goes on, and this approval starts nothing.
    if (count === 0) throw new HttpError(409, REPLACED_REQUEST_REFUSAL)
    await notifyBoardsOfTasks([taskId])
    await recordTaskActivity({ taskId, kind: 'APPROVED', actor: { kind: 'person', userId }, runId: args.runId })
    // A conversation that commissioned the run follows the run this approval starts.
    await taskRequestAnswered(args.runId, 'approve')
    void taskRunner.runTask(taskId, agent, startedBy, task?.runOnBehalfOfUserId ?? null)
  } else {
    // A conversation's run ended when it asked; approving starts its next run,
    // which is given what was approved with a note telling the agent, and sends
    // no visible message. A run started by a message into a task's session goes
    // on as its sender's, so they must still be on the task's project.
    const runPersonId = session.taskId ? await requireRunPersonOnTask(session.taskId, run) : null
    const { approved } = await siteRuntimeStore.approveRun(siteId, args.runId, userId)
    if (!approved) throw new HttpError(409, REPLACED_REQUEST_REFUSAL)
    try {
      await dispatchService.dispatchChatRun(session.id, CONTINUE_AFTER_APPROVAL, agent, session.model, {
        hideUserMessage: true,
        senderId: runPersonId ?? userId,
      })
    } catch (err) {
      rethrowDispatchErrorAsHttp(err)
    }
  }
  if (answeredTaskId) await markTaskNotificationsHandled(answeredTaskId)

  return { ok: true }
}

// ── rejectManifest ────────────────────────────────────────────────────────────


export const rejectManifest = async (
  args: RejectManifestArgs,
  context: any,
): Promise<ManifestAnswerResult> => {
  if (!context.user) throw new HttpError(401)
  requireRunNamed(args)
  if (typeof args.reason !== 'string') throw new HttpError(400, 'A reason is text, and may be empty')
  return rejectRequest(args, context.user.id)
}

/** Declines a run's request as `userId`: the one path a request is declined by, as approveRequest is for approving. */
export async function rejectRequest(args: RejectManifestArgs, userId: string): Promise<ManifestAnswerResult> {
  const { siteId, run, session, agent } = await resolveManifestRunContext(args.runId, args.sessionId)

  await assertCanMutateManifest(session, userId, 'reject')
  await requireCurrentRequest(siteId, run)

  // The run-row write (status CANCELLED, manifestStatus REJECTED, who and
  // when) happens on site's side of this call (dispatchHandler.ts's
  // handleRunReject); the run is not in hq's database.
  await siteRuntimeStore.rejectRun(siteId, args.runId, args.reason, userId)
  // Answered, by whoever: the request no longer waits in anyone's notifications.
  const answeredTaskId = run.taskId ?? session.taskId
  if (answeredTaskId) await markTaskNotificationsHandled(answeredTaskId)

  const io = (globalThis as any).__wasp_io__

  if (run.taskId) {
    // Task run: add a comment and hold the task for human review — do NOT
    // re-dispatch. Re-running would re-trigger the same manifest-approval
    // cycle; a rejected manifest must wait for a human (F-023). Both writes
    // are hq-owned control-plane data, unaffected by the split.
    await prisma.taskComment.create({
      data: {
        taskId: run.taskId,
        authorType: 'AGENT',
        agentId: run.agentId,
        runId: run.id,
        content: `__MANIFEST_REJECTED__: ${args.reason}`,
      },
    })
    // Held only if no newer run has been claimed since this request was read, as approving is: a run under
    // way keeps its state, and its own end settles the task.
    await prisma.task.updateMany({
      where: { id: run.taskId, runState: { notIn: TASK_RUN_UNDER_WAY } },
      data: { runState: 'RUN_BLOCKED', runStateReason: 'manifest rejected — awaiting human review' },
    })
    await notifyBoardsOfTasks([run.taskId])
    await recordTaskActivity({ taskId: run.taskId, kind: 'DENIED', actor: { kind: 'person', userId }, runId: run.id })
    await taskRequestAnswered(run.id, 'decline')
    io?.to(`task:${run.taskId}`).emit('manifestRejected', { runId: run.id, taskId: run.taskId, reason: args.reason })
  } else {
    // A conversation's run: the denial is the request's own answered state on
    // the site, never a message of the person's. Like an approval, the answer
    // starts the conversation's next run, told what was denied, so the agent
    // answers without it.
    io?.to(`session:${run.sessionId}`).emit('manifestRejected', {
      runId: run.id,
      sessionId: run.sessionId,
      reason: args.reason,
    })
    const runPersonId = session.taskId ? runOnBehalfOf(run.metadata) : null
    try {
      await dispatchService.dispatchChatRun(session.id, continueAfterDenial(run.pendingManifest, args.reason?.trim() || null), agent, session.model, {
        hideUserMessage: true,
        senderId: runPersonId ?? userId,
      })
    } catch (err) {
      rethrowDispatchErrorAsHttp(err)
    }
  }

  return { ok: true }
}

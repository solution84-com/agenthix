// A chat run's session owner is the real person driving the conversation, so
// only they may approve/reject its tool manifest. A task's session is shared on
// equal footing (every-screen-reviewed spec §3): anyone who works in the task's
// project may approve or reject its tool request — whoever started the run,
// and whether it was started by Run or by a message into the session. A
// project Viewer only watches (adr-0102). A task session whose task was
// deleted is its project's admins', as stopping it is (runActions.ts).
type SessionOwnership = { userId: string; sessionType: string; taskId: string | null } & SessionStorageBinding

async function assertCanMutateManifest(
  session: SessionOwnership,
  userId: string,
  verb: 'approve' | 'reject',
): Promise<void> {
  if (session.sessionType === 'chat') {
    if (session.userId !== userId) {
      throw new HttpError(403, `Only the session owner can ${verb} tools for this conversation`)
    }
    // Approving starts the conversation's next run, which is starting work;
    // rejecting starts nothing. That run acts in the project the chat is bound
    // to, so the owner must still belong to it (R-197).
    if (verb === 'approve') await requireStillEntitledToSessionProject(session, userId)
    return
  }
  const gerund = verb === 'approve' ? 'Approving' : 'Rejecting'
  if (session.taskId) {
    await requireTaskAccess(session.taskId, userId, `${gerund} this task-run manifest`)
  }
  // A personal project's task run is its person's alone, task or none (spec §4).
  const owner = personalSessionOwner(session)
  if (owner !== null && owner !== userId) {
    throw new HttpError(403, `${gerund} this task-run manifest requires being the person it belongs to`)
  }
  if (!session.taskId && owner === null) {
    await requireOrphanedSessionAdmin(session, userId, `${gerund} tools for a run whose task was deleted`)
  }
}

type ResolvedRun = { siteId: string; run: RunRow; session: AgentSession; agent: Agent }

/**
 * Resolves everything approve/reject need from just a runId (+ sessionId for
 * a chat run — see this file's own header comment for why that one case
 * needs a client-supplied hint). Every failure collapses to 404: the caller
 * cannot distinguish "wrong id" from "belongs to someone else" from the
 * error alone, matching this action's pre-existing behaviour.
 */
async function resolveManifestRunContext(runId: string, sessionId?: string): Promise<ResolvedRun> {
  const comment = await prisma.taskComment.findFirst({ where: { runId }, select: { taskId: true } })

  let siteId: string
  if (comment) {
    siteId = await dispatchService.resolveSiteIdForTask(comment.taskId)
  } else {
    if (!sessionId) throw new HttpError(404, 'Run not found')
    const chatSession = await prisma.agentSession.findUnique({
      where: { id: sessionId },
      select: { taskId: true, agentId: true, primaryOwnerType: true, primaryOwnerId: true, primaryWorkspaceId: true, userId: true, sessionType: true },
    })
    if (!chatSession) throw new HttpError(404, 'Run not found')
    siteId = await dispatchService.resolveSiteIdForSession(chatSession)
  }

  const run = await siteRuntimeStore.getRun(siteId, runId)
  if (!run) throw new HttpError(404, 'Run not found')

  const [session, agent] = await Promise.all([
    prisma.agentSession.findUnique({ where: { id: run.sessionId } }),
    prisma.agent.findUnique({ where: { id: run.agentId } }),
  ])
  if (!session) throw new HttpError(404, 'Run not found')
  if (!agent) throw new HttpError(404, 'Agent not found')

  return { siteId, run, session, agent }
}

async function requireRunPersonOnTask(taskId: string, run: RunRow): Promise<string | null> {
  const person = runOnBehalfOf(run.metadata)
  if (!person) return null
  const task = await prisma.task.findUnique({ where: { id: taskId }, select: { projectId: true } })
  if (!task || !(await personMayWorkInProject(task.projectId, person))) {
    throw new HttpError(409, 'The person this run is on behalf of can no longer work in its project')
  }
  return person
}


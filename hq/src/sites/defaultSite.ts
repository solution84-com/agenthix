import crypto from 'node:crypto'
import os from 'node:os'
import { prisma } from 'wasp/server'
import type { Prisma } from '@prisma/client'
import { credentialMatches, hashCredential } from './credentials'
import { Logger } from '../server/utils/logger'
import { demoOn } from '../demo/demoMode'

const logger = new Logger('Sites')

/**
 * hq's own site is configuration, not registration: one secret in hq's and the
 * site's environment. hq keeps the single `isDefault` row with the secret's
 * hash and the site presents the secret as its bearer credential. Nothing to
 * approve, nothing to repair — a wiped database on either side is rebuilt from
 * the same secret at the next start.
 */

const MIN_SECRET_LENGTH = 32
const NAME = /^[^\u0000-\u001f\u007f-\u009f\u2028\u2029]{1,64}$/

/**
 * HQ's own site is named after HQ's machine, as every site is after its own (host-management spec §6). The host service
 * gives the name (`HQ_MACHINE_NAME`); without it — a development run on the machine itself — the machine's host name.
 * A label only: nothing is found or trusted by it.
 */
export function hqMachineName(): string {
  const given = process.env.HQ_MACHINE_NAME?.trim()
  if (given && NAME.test(given)) return given
  const host = os.hostname().split('.')[0]
  return host && NAME.test(host) ? host : 'HQ'
}

export function pairingSecret(): string | null {
  const value = process.env.HQ_PAIRING_SECRET?.trim()
  return value && value.length >= MIN_SECRET_LENGTH ? value : null
}

/**
 * At most one default row is enforced here rather than by an index: the row is
 * found by `isDefault` and updated, never created a second time.
 */
export async function ensureDefaultSite(): Promise<'created' | 'updated' | 'unchanged' | 'unpaired'> {
  const secret = pairingSecret()
  if (!secret) return 'unpaired'
  const credentialHash = hashCredential(secret)

  const existing = await prisma.executionSite.findFirst({ where: { isDefault: true } })
  if (!existing) {
    await prisma.executionSite.create({
      data: {
        // A placeholder: the site's own id is adopted at its first connection.
        siteId: crypto.randomUUID(),
        label: hqMachineName(),
        status: 'REGISTERED',
        isDefault: true,
        credentialHash,
        // HQ's own site runs live previews unless a fleet admin turns them off; every other new site starts with them off.
        livePreviewsAllowed: true,
      },
    })
    return 'created'
  }

  const revoked = existing.status === 'REVOKED'
  // HQ may start on another machine — moved or restored there — and its site takes that machine's name.
  const label = hqMachineName()
  if (existing.credentialHash === credentialHash && !revoked && existing.label === label) return 'unchanged'
  await prisma.executionSite.update({
    where: { id: existing.id },
    data: { credentialHash, label, ...(revoked ? { status: 'REGISTERED' } : {}) },
  })
  return 'updated'
}

/**
 * Accepts the pairing secret from whatever site id the site presents. A site's
 * id is generated by its own database, so a wiped site database comes back with
 * a new one; the row adopts it.
 */
export async function authenticateDefaultSite(siteId: string, credential: string) {
  const row = await prisma.executionSite.findFirst({ where: { isDefault: true } })
  if (!row || row.status === 'REVOKED') return null
  if (!credentialMatches(credential, row.credentialHash)) return null
  if (row.siteId === siteId) return row
  return adoptSiteId(row, siteId, 'default site')
}

/**
 * Gives a site's row the id the site presents with its credential, clearing what named the old one. Used for the
 * default site and for a site the Fleet Console registered, whose row starts with a placeholder (fleet/siteCredentials.ts).
 * Null when the presented id already belongs to another site.
 */
export async function adoptSiteId<T extends { id: string; siteId: string }>(row: T, siteId: string, what: string) {
  try {
    const { adopted, cleared } = await prisma.$transaction(async (tx) => {
      const seen = await tx.executionSite.findUnique({ where: { id: row.id }, select: { lastSeenAt: true } })
      const adopted = await tx.executionSite.update({ where: { id: row.id }, data: { siteId } })
      return { adopted, cleared: keepsSeededPlacements(seen?.lastSeenAt ?? null) ? 0 : await clearRowsNamingSite(tx, row.id) }
    })
    logger.info(`${what} adopted a new site id — cleared ${cleared} stale row(s) naming the old one`)
    return adopted
  } catch (err) {
    // The presented id already belongs to another site — refuse, do not throw.
    if ((err as { code?: string }).code === 'P2002') return null
    throw err
  }
}

/**
 * The demo seeds its workspaces' placements on hq's own site before the site first connects (adr-0186), so the id the
 * site then presents replaces a placeholder, not an id a lost database had: nothing placed there is gone. Only in demo
 * mode, and only for a site never seen.
 */
function keepsSeededPlacements(lastSeenAt: Date | null): boolean {
  return lastSeenAt === null && demoOn()
}

/**
 * A workspace's placement holds the site row's own id as a plain string, with no foreign key. A site that comes back
 * with a new id of its own has lost its database, so the workspaces placed on it are gone with it.
 * Rows that follow the ExecutionSite row's own id (UserStoragePlacement,
 * Project) are not touched.
 */
async function clearRowsNamingSite(tx: Prisma.TransactionClient, rowId: string): Promise<number> {
  const where = { siteId: rowId }
  const results = [
    await tx.workspacePlacement.deleteMany({ where }),
  ]
  return results.reduce((total, r) => total + r.count, 0)
}
